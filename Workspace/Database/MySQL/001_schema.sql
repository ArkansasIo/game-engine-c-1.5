CREATE DATABASE IF NOT EXISTS game_engine CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE game_engine;

CREATE TABLE IF NOT EXISTS players (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 account_id VARCHAR(128) NOT NULL UNIQUE,
 display_name VARCHAR(64) NOT NULL UNIQUE,
 level INT UNSIGNED NOT NULL DEFAULT 1,
 experience BIGINT UNSIGNED NOT NULL DEFAULT 0,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS characters (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 player_id BIGINT UNSIGNED NOT NULL,
 class_id VARCHAR(32) NOT NULL,
 strength TINYINT NOT NULL DEFAULT 10,
 dexterity TINYINT NOT NULL DEFAULT 10,
 constitution TINYINT NOT NULL DEFAULT 10,
 intelligence TINYINT NOT NULL DEFAULT 10,
 wisdom TINYINT NOT NULL DEFAULT 10,
 charisma TINYINT NOT NULL DEFAULT 10,
 hp INT NOT NULL DEFAULT 1,
 max_hp INT NOT NULL DEFAULT 1,
 FOREIGN KEY (player_id) REFERENCES players(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS items (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 item_key VARCHAR(64) NOT NULL UNIQUE,
 name VARCHAR(128) NOT NULL,
 category VARCHAR(32) NOT NULL,
 rarity VARCHAR(32) NOT NULL DEFAULT 'Common',
 stack_limit INT UNSIGNED NOT NULL DEFAULT 99,
 base_value BIGINT UNSIGNED NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS inventories (
 character_id BIGINT UNSIGNED NOT NULL,
 item_id BIGINT UNSIGNED NOT NULL,
 quantity INT UNSIGNED NOT NULL DEFAULT 0,
 PRIMARY KEY(character_id,item_id),
 FOREIGN KEY(character_id) REFERENCES characters(id) ON DELETE CASCADE,
 FOREIGN KEY(item_id) REFERENCES items(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS quest_progress (
 character_id BIGINT UNSIGNED NOT NULL,
 quest_key VARCHAR(64) NOT NULL,
 state VARCHAR(24) NOT NULL,
 progress_json JSON NULL,
 PRIMARY KEY(character_id,quest_key),
 FOREIGN KEY(character_id) REFERENCES characters(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS audit_events (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 player_id BIGINT UNSIGNED NULL,
 event_type VARCHAR(64) NOT NULL,
 payload JSON NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX(created_at), INDEX(event_type)
);